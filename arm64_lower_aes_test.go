const arm64AESNamedForms = `
TEXT aesnamedforms(SB),$0-0
	AESE V0, V1
	AESD V2, V3
	AESMC V4, V5
	AESIMC V6, V7
	AESE V8.B16, V9.B16
	AESD V10.B16, V11.B16
	AESMC V12.B16, V13.B16
	AESIMC V14.B16, V15.B16
	RET
`

const arm64AESRawForms = `
TEXT aesrawforms(SB),$0-0
	WORD $0x4e284bfd // AESE V31.B16, V29.B16
	WORD $0x4e285ad3 // AESD V22.B16, V19.B16
	WORD $0x4e2869dc // AESMC V14.B16, V28.B16
	WORD $0x4e28799b // AESIMC V12.B16, V27.B16
	RET
`

func TestTranslateARM64AESCompleteGoAssemblerForms(t *testing.T) {
	requireARM64GoAssemblerResult(t, arm64AESNamedForms, true)
	requireARM64GoAssemblerResult(t, arm64AESRawForms, true)
	for name, source := range map[string]string{
		"named": arm64AESNamedForms,
		"raw":   arm64AESRawForms,
	} {
		t.Run(name, func(t *testing.T) {
			file, err := Parse(ArchARM64, source)
			if err != nil {
				t.Fatal(err)
			}
			for _, triple := range []string{
				"aarch64-apple-darwin",
				"aarch64-unknown-linux-gnu",
				"aarch64-pc-windows-msvc",
			} {
				t.Run(triple, func(t *testing.T) {
					function := "aesnamedforms"
					if name == "raw" {
						function = "aesrawforms"
					}
					ll, err := Translate(file, Options{
						TargetTriple: triple,
						Goarch:       "arm64",
						Sigs: map[string]FuncSig{
							function: {Name: function, Ret: Void},
						},
					})
					if err != nil {
						t.Fatal(err)
					}
					for _, want := range []string{
						"@llvm.aarch64.crypto.aese",
						"@llvm.aarch64.crypto.aesd",
						"@llvm.aarch64.crypto.aesmc",
						"@llvm.aarch64.crypto.aesimc",
						`"target-features"="+aes"`,
					} {
						if !strings.Contains(ll, want) {
							t.Fatalf("ARM64 AES lowering for %s omitted %q:\n%s", triple, want, ll)
						}
					}
					llc := findLLVM22Tool("llc")
					if llc == "" {
						t.Fatal("LLVM 22 llc not found")
					}
					compileLLVMToObject(t, llc, triple, "arm64-aes.ll", "arm64-aes.o", ll)
				})
			}
		})
	}
}

func TestTranslateARM64AESRejectsFormsOutsideGoAssemblerTable(t *testing.T) {
	for _, instruction := range []string{
		"AESD V1.B8, V2.B8",
		"AESE V1.D2, V2.D2",
		"AESIMC V1.S4, V2.S4",
		"AESE V1.B16, V2.B8",
		"AESMC V1.B16, V2",
		"AESE V1.B16, V2.B16, V3.B16",
	} {
		t.Run(strings.NewReplacer(" ", "_", ",", "", ".", "_").Replace(instruction), func(t *testing.T) {
			source := "TEXT badaes(SB),$0-0\n\t" + instruction + "\n\tRET\n"
			requireARM64GoAssemblerResult(t, source, false)
			file, err := Parse(ArchARM64, source)
			if err != nil {
				return
			}
			if _, err := Translate(file, Options{
				TargetTriple: "aarch64-unknown-linux-gnu",
				Goarch:       "arm64",
				Sigs: map[string]FuncSig{
					"badaes": {Name: "badaes", Ret: Void},
				},
			}); err == nil {
				t.Fatalf("Translate accepted %q outside Go 1.27's AES optab", instruction)
			}
		})
	}
}

func TestARM64RawAESDecoderCoversRegistersAndRejectsAdjacentEncodings(t *testing.T) {
	bases := map[string]uint32{
		"AESE":   0x4e284800,
		"AESD":   0x4e285800,
		"AESMC":  0x4e286800,
		"AESIMC": 0x4e287800,
	}
	for op, base := range bases {
		for source := 0; source < 32; source++ {
			for destination := 0; destination < 32; destination++ {
				word := base | uint32(source<<5) | uint32(destination)
				form, ok := decodeARM64RawAES(word)
				if !ok || form.op != Op(op) || form.source != source || form.destination != destination {
					t.Fatalf("decode %#08x = %#v, %v; want %s V%d, V%d", word, form, ok, op, source, destination)
				}
			}
		}
	}
	for _, word := range []uint32{
		0x0e284800, // invalid Q/opcode prefix
		0x4e284c00, // adjacent opcode field
		0x4e285400, // adjacent opcode field
		0x4e287c00, // adjacent opcode field
	} {
		if form, ok := decodeARM64RawAES(word); ok {
			t.Fatalf("AES decoder accepted adjacent encoding %#08x as %#v", word, form)
		}
	}
}

