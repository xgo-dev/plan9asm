// Translate converts a parsed Plan 9 asm File into LLVM IR text (`.ll`).
//
// The generated text is produced from an llvm.Module to keep textual emission
// consistent with the LLVM printer.
func Translate(file *File, opt Options) (string, error) {
	mod, err := TranslateModule(file, opt)
	if err != nil {
		return "", err
	}
	defer mod.Dispose()
	return mod.String(), nil
}

// translateIRText builds textual LLVM IR prior to module parsing.
func translateIRText(file *File, opt Options) (string, error) {
	if file == nil {
		return "", fmt.Errorf("nil file")
	}
	if !opt.X87Mode.Valid() {
		return "", fmt.Errorf("invalid x87 mode %d", opt.X87Mode)
	}
	if len(file.Funcs) == 0 && len(file.Data) == 0 && len(file.Globl) == 0 {
		return "", fmt.Errorf("empty file")
	}

	resolve := opt.ResolveSym
	if resolve == nil {
		resolve = func(s string) string { return s }
	}
	if !opt.WASMABI.Valid() {
		return "", fmt.Errorf("invalid wasm ABI %d", opt.WASMABI)
	}
	if file.Arch == ArchWASM && opt.WASMABI == WASMABIDirect {
		for _, fn := range file.Funcs {
			if !wasm.NeedsIncomingContext(fn) {
				continue
			}
			name := resolve(fn.Sym)
			sig, ok := opt.Sigs[name]
			if !ok || sig.WASMContext != "" {
				continue
			}
			sig.WASMContext = Ptr
			opt.Sigs[name] = sig
		}
	}

	layouts, err := dataGlobalLayouts(file, resolve, opt.Goarch)
	if err != nil {
		return "", err
	}
	file, err = bindTLSOffsets(file, layouts, resolve, opt.TargetTriple)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("; Generated by llgo internal/plan9asm (prototype)\n")
	if opt.TargetTriple != "" {
		fmt.Fprintf(&b, "target triple = %q\n\n", opt.TargetTriple)
	}
	// Keep translate.go as the cross-platform pipeline entry.
	// Architecture-specific declarations live in arch-specific files.
	emitArchPrelude(&b, file, resolve, opt.Goarch, opt.WASMABI, opt.X87Mode)

	emitExternSBGlobals(&b, file, resolve, opt.Sigs)

	if len(file.Data) != 0 || len(file.Globl) != 0 {
		if err := emitDataLayouts(&b, file, layouts, resolve, opt); err != nil {
			return "", err
		}
		b.WriteString("\n")
	}

	emitExternFuncDecls(&b, file, resolve, opt.Sigs, opt.WASMABI)

	var kuserCAS map[string]bool
	if file.Arch == ArchARM {
		kuserCAS = arm.CollectKuserCASFuncs(file.Funcs, resolve)
	}

	var body strings.Builder
	attrRegistry := newFeatureAttrRegistry()
	for i := range file.Funcs {
		fn := &file.Funcs[i]
		name := resolve(fn.Sym)
		sig, ok := opt.Sigs[name]
		if !ok {
			return "", fmt.Errorf("missing signature for %q", name)
		}
		if sig.Name == "" {
			sig.Name = name
		}
		if sig.Name != name {
			return "", fmt.Errorf("signature name mismatch: %q vs %q", sig.Name, name)
		}
		if sig.Ret == "" {
			return "", fmt.Errorf("missing return type for %q", name)
		}
		if err := validateResolvedImmediates(file.Arch, *fn); err != nil {
			return "", fmt.Errorf("%s: %w", name, err)
		}
		features := inferFuncTargetFeaturesForGOARCH(file.Arch, opt.Goarch, *fn)
		sig.Attrs, err = attrRegistry.merge(sig.Attrs, features)
		if err != nil {
			return "", fmt.Errorf("%s: %w", name, err)
		}

		if file.Arch == ArchARM && arm.FuncNeedsCFG(*fn) {
			if err := arm.TranslateFuncWithKuserCAS(&body, *fn, sig, resolve, opt.Sigs, kuserCAS, opt.TargetTriple, opt.AnnotateSource); err != nil {
				return "", fmt.Errorf("%s: %w", name, err)
			}
			body.WriteString("\n")
			continue
		}
		if file.Arch == ArchARM64 && arm64.FuncNeedsCFG(*fn) {
			if err := arm64.TranslateFunc(&body, *fn, sig, resolve, opt.Sigs, opt.AnnotateSource, opt.TargetTriple); err != nil {
				return "", fmt.Errorf("%s: %w", name, err)
			}
			body.WriteString("\n")
			continue
		}
		if file.Arch == ArchAMD64 && (opt.Goarch == "386" || (opt.Goarch == "amd64" && x86.FuncNeedsCFG(*fn))) {
			callOpt := opt
			callOpt.ResolveSym = resolve
			if err := x86.TranslateFuncWithOptions(&body, *fn, sig, callOpt); err != nil {
				return "", fmt.Errorf("%s: %w", name, err)
			}
			body.WriteString("\n")
			continue
		}
		if file.Arch == ArchWASM {
			if err := wasm.TranslateFunc(&body, *fn, sig, resolve, opt.Sigs, opt.WASMABI, opt.AnnotateSource); err != nil {
				return "", fmt.Errorf("%s: %w", name, err)
			}
			body.WriteString("\n")
			continue
		}
		if err := translateFuncLinear(&body, file.Arch, *fn, sig, opt.AnnotateSource); err != nil {
			return "", fmt.Errorf("%s: %w", name, err)
		}
		body.WriteString("\n")
	}
	bodyText := body.String()
	if extraDecls := asm.CollectMissingLLVMIntrinsicDecls(b.String(), bodyText); extraDecls != "" {
		b.WriteString(extraDecls)
	}
	b.WriteString(bodyText)
	attrRegistry.emit(&b)
	return b.String(), nil
}

func validateResolvedImmediates(arch Arch, fn Func) error {
	if arch != ArchARM && arch != ArchWASM {
		return nil
	}
	for _, ins := range fn.Instrs {
		for _, arg := range ins.Args {
			if arg.Kind == OpImm && arg.ImmRaw != "" {
				return fmt.Errorf("unresolved symbolic immediate %q", arg.ImmRaw)
			}
			if arch == ArchWASM && arg.Kind == OpMem && arg.Mem.OffRaw != "" {
				return fmt.Errorf("unresolved wasm memory offset %q", arg.Mem.OffRaw)
			}
		}
	}
	return nil
}

func emitExternFuncDecls(b *strings.Builder, file *File, resolve func(string) string, sigs map[string]FuncSig, wasmABI WASMABI) {
	defined := map[string]bool{}
	for i := range file.Funcs {
		defined[resolve(file.Funcs[i].Sym)] = true
	}

	// Deterministic order for tests/debugging.
	names := make([]string, 0, len(sigs))
	for name := range sigs {
		if defined[name] {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		sig := sigs[name]
		if sig.Ret == "" {
			continue
		}
		if file.Arch == ArchWASM && wasmABI == WASMABIGo && !sig.WASMNative {
			fmt.Fprintf(b, "declare i32 %s(i32)\n", asm.LLVMGlobal(asm.FuncSigSymbol(name, sig)))
			continue
		}
		fmt.Fprintf(b, "declare %s %s(", sig.Ret, asm.LLVMGlobal(asm.FuncSigSymbol(name, sig)))
		argIndex := 0
		if sig.WASMContext != "" {
			b.WriteString(string(sig.WASMContext))
			argIndex++
		}
		for _, t := range sig.Args {
			if argIndex > 0 {
				b.WriteString(", ")
			}
			b.WriteString(string(t))
			argIndex++
		}
		b.WriteString(")")
		if sig.Attrs != "" {
			b.WriteString(" " + sig.Attrs)
		}
		b.WriteString("\n")
	}
	if len(names) != 0 {
		b.WriteString("\n")
	}
}

func emitExternSBGlobals(b *strings.Builder, file *File, resolve func(string) string, sigs map[string]FuncSig) {
	resolveSBBase := func(base string) string { return resolveDataSymbol(base, resolve) }

	// Collect base symbols of SB refs with numeric offsets. These are almost always
	// global variables whose address is computed via GEP in the lowering.
	need := map[string]bool{}
	defined := map[string]bool{}

	// Anything in DATA/GLOBL will be defined in this module.
	for _, g := range file.Globl {
		defined[resolveSBBase(g.Sym)] = true
	}
	for _, d := range file.Data {
		defined[resolveSBBase(d.Sym)] = true
	}
	for _, fn := range file.Funcs {
		defined[resolve(fn.Sym)] = true
	}

	for _, d := range file.Data {
		if d.Addr == "" {
			continue
		}
		base, _, err := parseDataAddress(d.Addr)
		name := resolveSBBase(base)
		if _, function := sigs[name]; err == nil && name != "" && !defined[name] && !function {
			need[name] = true
		}
	}

	for _, fn := range file.Funcs {
		for _, ins := range fn.Instrs {
			opName := strings.ToUpper(string(ins.Op))
			for _, arg := range ins.Args {
				if arg.Kind != OpSym {
					continue
				}
				s := strings.TrimSpace(arg.Sym)
				base, off, ok := asm.ParseSBRef(s)
				if !ok || base == "" {
					continue
				}
				base = strings.TrimPrefix(base, "$")
				if off == 0 {
					// Bare symbol refs are usually global data addresses
					// (e.g. MOVQ runtime·vdsoGettimeofdaySym(SB), AX). Exclude only
					// control-flow ops that use symbol operands as branch/call targets.
					switch opName {
					case "JMP", "JE", "JEQ", "JZ", "JNE", "JNZ",
						"JL", "JLT", "JLE", "JG", "JGT", "JGE", "JS", "JNS",
						"JB", "JBE", "JA", "JAE", "JLS", "JNA",
						"JC", "JNC", "JCC", "CALL", "CALLNORESUME", "WASMCALL", "BL", "B":
						continue
					}
				}
				name := resolveSBBase(base)
				if name != "" && !defined[name] {
					if _, fn := sigs[name]; fn {
						continue
					}
					need[name] = true
				}
			}
		}
	}

	if len(need) == 0 {
		return
	}
	names := make([]string, 0, len(need))
	for name := range need {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(b, "%s = external global i8\n", asm.LLVMGlobal(name))
	}
	b.WriteString("\n")
}

func resolveDataSymbol(sym string, resolve func(string) string) string {
	sym = strings.TrimSpace(sym)
	if sym == "" {
		return ""
	}
	if !strings.ContainsAny(sym, "·/.") {
		sym = "·" + sym
	}
	return resolve(sym)
}

// parseDataAddress keeps the assembler's constant addend separate from the
// referenced symbol, including expressions produced by macro expansion.
func parseDataAddress(addr string) (string, int64, error) {
	s, ok := strings.CutSuffix(strings.TrimSpace(addr), "(SB)")
	if !ok || s == "" {
		return "", 0, fmt.Errorf("invalid DATA address %q", addr)
	}
	return asm.ParseDataSymbol(s)
}

type dataGlobalLayout struct {
	name        string
	size        int64
	declared    bool
	readOnly    bool
	duplicateOK bool
	local       bool
	tlsOffset   bool
	stmts       []DataStmt
}

var dataFlagToken = regexp.MustCompile(`\b[A-Z][A-Z_0-9]*\b`)

func dataFlagValue(name string) string {
	switch name {
	case "DUPOK":
		return "2"
	case "RODATA":
		return "8"
	case "NOPTR":
		return "16"
	case "LOCAL":
		return "128"
	case "TLSBSS":
		return "256"
	}
	return name
}

func sourcePointerWidth(arch Arch, goarch string) int64 {
	if arch == ArchARM || goarch == "386" {
		return 4
	}
	return 8
}

func dataGlobalLayouts(file *File, resolve func(string) string, goarch string) ([]*dataGlobalLayout, error) {
	var layouts []*dataGlobalLayout
	byName := make(map[string]*dataGlobalLayout)
	get := func(sym string) *dataGlobalLayout {
		name := resolveDataSymbol(sym, resolve)
		if g := byName[name]; g != nil {
			return g
		}
		g := &dataGlobalLayout{name: name}
		byName[name] = g
		layouts = append(layouts, g)
		return g
	}
	for _, decl := range file.Globl {
		g := get(decl.Sym)
		if decl.Size < 0 {
			return nil, fmt.Errorf("GLOBL %s: unresolved size: %w", g.name, ErrProbeNeedsContext)
		}
		if decl.Size > maxDataGlobalSize {
			return nil, fmt.Errorf("GLOBL %s: size %d exceeds %d-byte limit", g.name, decl.Size, maxDataGlobalSize)
		}
		var flags uint64
		if decl.Flags != "" {
			var ok bool
			flags, ok = asm.ParseImmExpr(dataFlagToken.ReplaceAllStringFunc(strings.TrimPrefix(decl.Flags, "$"), dataFlagValue))
			if !ok {
				return nil, fmt.Errorf("GLOBL %s: unresolved flags %q: %w", g.name, decl.Flags, ErrProbeNeedsContext)
			}
		}
		if g.declared {
			return nil, fmt.Errorf("GLOBL %s: duplicate declaration", g.name)
		}
		g.duplicateOK, g.local = flags&2 != 0, flags&128 != 0
		g.size, g.declared, g.readOnly = decl.Size, true, flags&8 != 0
		// cmd/internal/obj.GloblPos gives RODATA and NOPTR precedence over TLSBSS.
		g.tlsOffset = flags&(8|16|256) == 256
	}
	for _, d := range file.Data {
		d = d.WithPointerWidth(sourcePointerWidth(file.Arch, goarch))
		g := get(d.Sym)
		end, err := dataStmtEnd(d)
		if err != nil {
			return nil, err
		}
		if end > g.size {
			if g.declared {
				return nil, fmt.Errorf("DATA %s: range [%d,%d) exceeds size %d", g.name, d.Off, end, g.size)
			}
			g.size = end
		}
		g.stmts = append(g.stmts, d)
	}
	sort.Slice(layouts, func(i, j int) bool { return layouts[i].name < layouts[j].name })
	for _, g := range layouts {
		sort.Slice(g.stmts, func(i, j int) bool { return g.stmts[i].Off < g.stmts[j].Off })
		var end int64
		for _, d := range g.stmts {
			if d.Off < end {
				return nil, fmt.Errorf("DATA %s: overlapping initializer at byte %d", g.name, d.Off)
			}
			end = d.Off + d.Width
		}
	}
	return layouts, nil
}

// bindTLSOffsets identifies offset relocations before lowering. Preserve the
// caller's parsed assembly: it may be reused for multiple targets.
func bindTLSOffsets(file *File, layouts []*dataGlobalLayout, resolve func(string) string, triple string) (*File, error) {
	var offsets map[string]bool
	for _, g := range layouts {
		if !g.tlsOffset {
			continue
		}
		if file.Arch != ArchARM && file.Arch != ArchARM64 {
			return nil, fmt.Errorf("GLOBL %s: TLSBSS binding for %s: %w", g.name, file.Arch, ErrProbeNeedsContext)
		}
		if len(g.stmts) != 0 {
			return nil, fmt.Errorf("DATA %s: TLSBSS has no static initializer: %w", g.name, ErrProbeNeedsContext)
		}
		if offsets == nil {
			offsets = make(map[string]bool)
		}
		offsets[g.name] = true
	}
	if len(offsets) == 0 {
		return file, nil
	}
	if targetInstructionSet(triple) != file.Arch || !hasELFTLS(triple) {
		return nil, fmt.Errorf("TLSBSS needs a native ELF TLS target, got %q: %w", triple, ErrProbeNeedsContext)
	}
	for _, g := range layouts {
		for _, d := range g.stmts {
			if d.Addr == "" {
				continue
			}
			base, _, err := parseDataAddress(d.Addr)
			if err != nil {
				return nil, err
			}
			if offsets[resolveDataSymbol(base, resolve)] {
				return nil, fmt.Errorf("DATA %s: address of TLSBSS symbol %s: %w", g.name, base, ErrProbeNeedsContext)
			}
		}
	}
	load := Op("MOVD")
	if file.Arch == ArchARM {
		load = "MOVW"
	}
	out := *file
	out.Funcs = append([]Func(nil), file.Funcs...)
	for fi, fn := range file.Funcs {
		var bound []Instr
		for ii, ins := range fn.Instrs {
			for i, a := range ins.Args {
				symbol := a.Sym
				if a.Kind == OpMem {
					symbol = a.Mem.Sym
				} else if a.Kind != OpSym {
					continue
				}
				raw := strings.TrimPrefix(symbol, "$")
				if !strings.HasSuffix(raw, "(SB)") {
					continue
				}
				base, delta, err := parseDataAddress(raw)
				plain := a.Kind == OpSym && raw == symbol && err == nil && delta == 0
				if !offsets[resolveDataSymbol(base, resolve)] {
					continue
				}
				if plain && i == 0 && ins.Op == load && len(ins.Args) == 2 {
					dst := ins.Args[1]
					if dst.Kind == OpReg && strings.HasPrefix(string(dst.Reg), "R") {
						if bound == nil {
							bound = append([]Instr(nil), fn.Instrs...)
							out.Funcs[fi].Instrs = bound
						}
						bound[ii].Args = append([]Operand(nil), ins.Args...)
						bound[ii].Args[i] = Operand{Kind: asm.OpTLSOffset, Sym: resolveDataSymbol(base, resolve)}
						continue
					}
				}
				return nil, fmt.Errorf("%s: TLSBSS %s requires a whole-word offset load: %w", ins.Op, base, ErrProbeNeedsContext)
			}
		}
	}
	return &out, nil
}

func hasELFTLS(triple string) bool {
	parts := strings.Split(strings.ToLower(triple), "-")
	native := false
	for _, part := range parts[1:] {
		os := strings.TrimRight(part, "0123456789.")
		switch os {
		case "linux", "freebsd", "netbsd", "dragonfly":
			native = true
		case "openbsd", "ohos", "liteos":
			return false
		case "android", "androideabi":
			// LLVM 22 defaults to emutls below Android API level 29,
			// including when the triple omits the API level.
			level, _, _ := strings.Cut(part[len(os):], ".")
			v, err := strconv.Atoi(level)
			if err != nil || v < 29 {
				return false
			}
		}
	}
	return native
}

// initialBytes leaves relocation fields zero for the separate relocation emitter.
func (g *dataGlobalLayout) initialBytes() ([]byte, error) {
	if len(g.stmts) == 0 {
		return nil, nil
	}
	buf, err := makeDataGlobal(g.name, g.size)
	if err != nil {
		return nil, err
	}
	for _, d := range g.stmts {
		if d.Addr != "" {
			continue
		}
		payload, err := dataStmtPayload(d)
		if err != nil {
			return nil, err
		}
		copy(buf[d.Off:], payload)
	}
	return buf, nil
}

func emitDataGlobals(b *strings.Builder, file *File, resolve func(string) string) error {
	layouts, err := dataGlobalLayouts(file, resolve, "")
	if err != nil {
		return err
	}
	return emitDataLayouts(b, file, layouts, resolve, Options{})
}

func emitDataLayouts(b *strings.Builder, file *File, layouts []*dataGlobalLayout, resolve func(string) string, opt Options) error {
	ptrBytes := sourcePointerWidth(file.Arch, opt.Goarch)
	cpu, _, _ := strings.Cut(strings.ToLower(opt.TargetTriple), "-")
	wasm32 := cpu == "wasm32" || cpu == "" && file.Arch == ArchWASM
	for _, g := range layouts {
		buf, err := g.initialBytes()
		if err != nil {
			return err
		}
		kind := "global"
		if g.readOnly {
			kind = "constant"
		}
		var types, fields []string
		addBytes := func(bytes []byte) {
			if len(bytes) != 0 {
				typ := fmt.Sprintf("[%d x i8]", len(bytes))
				types = append(types, typ)
				fields = append(fields, typ+" "+llvmI8ArrayInit(bytes))
			}
		}
		var pos int64
		for _, d := range g.stmts {
			if d.Addr == "" {
				continue
			}
			base, addend, err := parseDataAddress(d.Addr)
			if err != nil {
				return err
			}
			if d.Width != ptrBytes {
				return fmt.Errorf("DATA %s+%d/%d: invalid %d-byte address %q", g.name, d.Off, d.Width, ptrBytes, d.Addr)
			}
			addBytes(buf[pos:d.Off])
			name := resolveDataSymbol(base, resolve)
			target := asm.LLVMGlobal(asm.FuncSigSymbol(name, opt.Sigs[name]))
			relocWidth := d.Width
			if d.Width == 8 && wasm32 {
				// Go wasm stores addresses in 8-byte words, while wasm32
				// object relocations hold a 4-byte linear/table address.
				relocWidth = 4
			}
			typ := fmt.Sprintf("i%d", 8*relocWidth)
			if addend != 0 {
				target = fmt.Sprintf("getelementptr (i8, ptr %s, i64 %d)", target, addend)
			}
			types = append(types, typ)
			fields = append(fields, fmt.Sprintf("%s ptrtoint (ptr %s to %s)", typ, target, typ))
			pos = d.Off + relocWidth
		}
		fmt.Fprintf(b, "%s = ", asm.LLVMGlobal(g.name))
		if g.duplicateOK {
			b.WriteString("weak ")
		}
		if g.local {
			b.WriteString("hidden ")
		}
		if g.tlsOffset {
			b.WriteString("thread_local(localexec) ")
		}
		fmt.Fprintf(b, "%s ", kind)
		if len(fields) == 0 {
			fmt.Fprintf(b, "[%d x i8] %s", g.size, llvmI8ArrayInit(buf))
		} else {
			addBytes(buf[pos:])
			fmt.Fprintf(b, "<{ %s }> <{ %s }>", strings.Join(types, ", "), strings.Join(fields, ", "))
		}
		fmt.Fprintf(b, ", align %d\n", bestAlign(g.size))
	}
	return nil
}

// Data globals are currently materialized as byte slices and then as LLVM
// constant arrays. Bound their size so malformed input cannot exhaust the
// translator's memory before LLVM sees it. The Go standard library's largest
// assembly global is only a few KiB.
const maxDataGlobalSize int64 = 64 << 20

func dataStmtEnd(d DataStmt) (int64, error) {
	if d.Off < 0 {
		return 0, fmt.Errorf("DATA %s: invalid offset %d", d.Sym, d.Off)
	}
	if d.Width <= 0 || d.Width > maxDataGlobalSize || d.Off > maxDataGlobalSize-d.Width {
		return 0, fmt.Errorf("DATA %s: range off=%d width=%d exceeds %d-byte limit", d.Sym, d.Off, d.Width, maxDataGlobalSize)
	}
	return d.Off + d.Width, nil
}

func makeDataGlobal(name string, size int64) ([]byte, error) {
	if size < 0 || size > maxDataGlobalSize {
		return nil, fmt.Errorf("global %s: size %d exceeds %d-byte limit", name, size, maxDataGlobalSize)
	}
	return make([]byte, size), nil
}

func dataStmtPayload(d DataStmt) ([]byte, error) {
	if d.Addr != "" {
		return nil, fmt.Errorf("DATA %s: address %q requires a relocation", d.Sym, d.Addr)
	}
	if d.Width <= 0 {
		return nil, fmt.Errorf("DATA %s: invalid width %d", d.Sym, d.Width)
	}
	if d.Width > maxDataGlobalSize {
		return nil, fmt.Errorf("DATA %s: width %d exceeds %d-byte limit", d.Sym, d.Width, maxDataGlobalSize)
	}
	payload := make([]byte, d.Width)
	if d.Payload != nil {
		if int64(len(d.Payload)) > d.Width {
			return nil, fmt.Errorf("DATA %s: string payload is %d bytes, exceeds width %d", d.Sym, len(d.Payload), d.Width)
		}
		copy(payload, d.Payload)
		return payload, nil
	}
	// Plan 9 asm DATA encodes integer immediates little-endian on the
	// architectures supported by this translator.
	v := d.Value
	for i := range payload {
		payload[i] = byte(v & 0xff)
		v >>= 8
	}
	return payload, nil
}

func bestAlign(size int64) int64 {
	// Conservative alignment guess good enough for stdlib constant tables.
	switch {
	case size >= 16 && size%16 == 0:
		return 16
	case size >= 8 && size%8 == 0:
		return 8
	case size >= 4 && size%4 == 0:
		return 4
	case size >= 2 && size%2 == 0:
		return 2
	default:
		return 1
	}
}

func llvmI8ArrayInit(b []byte) string {
	if len(b) == 0 {
		return "zeroinitializer"
	}
	var sb strings.Builder
	sb.WriteString("[")
	for i, v := range b {
		if i != 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "i8 %d", int(v))
	}
	sb.WriteString("]")
	return sb.String()
}

func translateFuncLinear(b *strings.Builder, arch Arch, fn Func, sig FuncSig, annotateSource bool) error {
	// Function header.
	fmt.Fprintf(b, "define %s %s(", sig.Ret, asm.LLVMGlobal(sig.Name))
	for i, t := range sig.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%s %%arg%d", t, i)
	}
	b.WriteString(")")
	if sig.Attrs != "" {
		b.WriteString(" " + sig.Attrs)
	}
	b.WriteString(" {\n")
	b.WriteString("entry:\n")

	type ssaVal struct {
		typ LLVMType
		val string // either constant ("0") or SSA ("%t1")
	}

	isSSA := func(v string) bool { return strings.HasPrefix(v, "%") }

	// Register SSA values.
	reg := map[Reg]ssaVal{}
	results := make([]ssaVal, len(sig.Frame.Results))
	haveResult := make([]bool, len(sig.Frame.Results))

	// Initialize a few common arg registers for ABIInternal-style asm.
	// This is currently best-effort; the prototype primarily targets stdlib
	// asm that uses FP slots.
	switch arch {
	case ArchARM:
		if len(sig.ArgRegs) > 0 {
			for i := 0; i < len(sig.Args) && i < len(sig.ArgRegs); i++ {
				reg[sig.ArgRegs[i]] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		} else {
			for i := 0; i < len(sig.Args) && i < 4; i++ {
				reg[Reg(fmt.Sprintf("R%d", i))] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		}
	case ArchARM64:
		if len(sig.ArgRegs) > 0 {
			for i := 0; i < len(sig.Args) && i < len(sig.ArgRegs); i++ {
				reg[sig.ArgRegs[i]] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		} else {
			for i := 0; i < len(sig.Args) && i < 8; i++ {
				reg[Reg(fmt.Sprintf("R%d", i))] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		}
	case ArchAMD64:
		if len(sig.ArgRegs) > 0 {
			for i := 0; i < len(sig.Args) && i < len(sig.ArgRegs); i++ {
				reg[sig.ArgRegs[i]] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		} else {
			// SysV-ish mapping (C ABI): DI, SI, DX, CX, R8, R9.
			x86 := []Reg{DI, SI, DX, CX, Reg("R8"), Reg("R9")}
			for i := 0; i < len(sig.Args) && i < len(x86); i++ {
				reg[x86[i]] = ssaVal{typ: sig.Args[i], val: fmt.Sprintf("%%arg%d", i)}
			}
		}
	}
	tmp := 0
	newTmp := func() string {
		tmp++
		return fmt.Sprintf("t%d", tmp)
	}

	emitCast := func(v ssaVal, to LLVMType) (ssaVal, error) {
		if v.typ == "" {
			return ssaVal{}, fmt.Errorf("missing type for value %q", v.val)
		}
		if v.typ == to {
			return v, nil
		}
		// Only support integer casts for now (enough for internal/cpu asm).
		switch {
		case v.typ == I64 && (to == I1 || to == I8 || to == I16):
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = trunc i64 %s to %s\n", name, v.val, to)
			return ssaVal{typ: to, val: "%" + name}, nil
		case v.typ == I64 && to == I32:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = trunc i64 %s to i32\n", name, v.val)
			return ssaVal{typ: I32, val: "%" + name}, nil
		case (v.typ == I1 || v.typ == I8 || v.typ == I16) && to == I32:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = zext %s %s to i32\n", name, v.typ, v.val)
			return ssaVal{typ: I32, val: "%" + name}, nil
		case v.typ == I32 && to == I64:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = zext i32 %s to i64\n", name, v.val)
			return ssaVal{typ: I64, val: "%" + name}, nil
		case (v.typ == I1 || v.typ == I8 || v.typ == I16 || v.typ == I32) && to == I64:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = zext %s %s to i64\n", name, v.typ, v.val)
			return ssaVal{typ: I64, val: "%" + name}, nil
		case (v.typ == I32 || v.typ == I16 || v.typ == I8) && to == I1:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = trunc %s %s to i1\n", name, v.typ, v.val)
			return ssaVal{typ: I1, val: "%" + name}, nil
		case (v.typ == I32 || v.typ == I16) && to == I8:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = trunc %s %s to i8\n", name, v.typ, v.val)
			return ssaVal{typ: I8, val: "%" + name}, nil
		case v.typ == I32 && to == I16:
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = trunc i32 %s to i16\n", name, v.val)
			return ssaVal{typ: I16, val: "%" + name}, nil
		case (v.typ == I1 || v.typ == I8 || v.typ == I16 || v.typ == I32 || v.typ == I64) && (to == LLVMType("float") || to == LLVMType("double")):
			srcTy := v.typ
			srcVal := v.val
			if v.typ == I1 || v.typ == I8 || v.typ == I16 {
				w := newTmp()
				fmt.Fprintf(b, "  %%%s = zext %s %s to i32\n", w, v.typ, v.val)
				srcTy = I32
				srcVal = "%" + w
			}
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = uitofp %s %s to %s\n", name, srcTy, srcVal, to)
			return ssaVal{typ: to, val: "%" + name}, nil
		case (v.typ == LLVMType("float") || v.typ == LLVMType("double")) && (to == I1 || to == I8 || to == I16 || to == I32 || to == I64):
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = fptoui %s %s to %s\n", name, v.typ, v.val, to)
			return ssaVal{typ: to, val: "%" + name}, nil
		case v.typ == Ptr && to == I32:
			if !isSSA(v.val) {
				if v.val == "null" || v.val == "0" {
					return ssaVal{typ: I32, val: "0"}, nil
				}
				return ssaVal{}, fmt.Errorf("unsupported non-SSA ptr cast source %q", v.val)
			}
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = ptrtoint ptr %s to i32\n", name, v.val)
			return ssaVal{typ: I32, val: "%" + name}, nil
		case v.typ == Ptr && to == I64:
			// stdlib asm often moves pointers through GPRs (e.g. MOVD ptr+0(FP), R0).
			// Linear lowering models GPRs as integer SSA values, so support ptr<->i64.
			if !isSSA(v.val) {
				if v.val == "0" || v.val == "null" {
					return ssaVal{typ: I64, val: "0"}, nil
				}
				return ssaVal{}, fmt.Errorf("unsupported non-SSA ptr cast source %q", v.val)
			}
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = ptrtoint ptr %s to i64\n", name, v.val)
			return ssaVal{typ: I64, val: "%" + name}, nil
		case v.typ == I64 && to == Ptr:
			src := v.val
			if !isSSA(src) {
				name := newTmp()
				fmt.Fprintf(b, "  %%%s = add i64 %s, 0\n", name, src)
				src = "%" + name
			}
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = inttoptr i64 %s to ptr\n", name, src)
			return ssaVal{typ: Ptr, val: "%" + name}, nil
		case v.typ == I32 && to == Ptr:
			src := v.val
			if !isSSA(src) {
				name := newTmp()
				fmt.Fprintf(b, "  %%%s = add i32 %s, 0\n", name, src)
				src = "%" + name
			}
			name := newTmp()
			fmt.Fprintf(b, "  %%%s = inttoptr i32 %s to ptr\n", name, src)
			return ssaVal{typ: Ptr, val: "%" + name}, nil
		default:
			return ssaVal{}, fmt.Errorf("unsupported cast %s -> %s", v.typ, to)
		}
	}

	zero := func(t LLVMType) (ssaVal, error) {
		switch t {
		case I1, I8, I16, I32, I64:
			return ssaVal{typ: t, val: "0"}, nil
		case Ptr:
			return ssaVal{typ: Ptr, val: "null"}, nil
		default:
			return ssaVal{typ: t, val: asm.LLVMZeroValue(t)}, nil
		}
	}

	fpParamSlot := func(off int64) (FrameSlot, bool) {
		for _, s := range sig.Frame.Params {
			if s.Offset == off {
				return s, true
			}
		}
		return FrameSlot{}, false
	}
	fpResultIndex := func(off int64) (int, LLVMType, bool) {
		for _, s := range sig.Frame.Results {
			if s.Offset == off {
				return s.Index, s.Type, true
			}
		}
		return 0, "", false
	}

	addrOfMem := func(mem MemRef) (string, error) {
		cur := "0"
		if mem.Base != "" {
			bv, ok := reg[mem.Base]
			if ok {
				cast, err := emitCast(bv, I64)
				if err != nil {
					return "", err
				}
				cur = cast.val
			}
		}
		if mem.Index != "" {
			iv := ssaVal{typ: I64, val: "0"}
			if v, ok := reg[mem.Index]; ok {
				cast, err := emitCast(v, I64)
				if err != nil {
					return "", err
				}
				iv = cast
			}
			scale := mem.Scale
			if scale == 0 {
				scale = 1
			}
			mul := newTmp()
			fmt.Fprintf(b, "  %%%s = mul i64 %s, %d\n", mul, iv.val, scale)
			add := newTmp()
			fmt.Fprintf(b, "  %%%s = add i64 %s, %%%s\n", add, cur, mul)
			cur = "%" + add
		}
		if mem.Off != 0 {
			add := newTmp()
			fmt.Fprintf(b, "  %%%s = add i64 %s, %d\n", add, cur, mem.Off)
			cur = "%" + add
		}
		return cur, nil
	}

	var valueOf func(op Operand) (ssaVal, error)
	valueOf = func(op Operand) (ssaVal, error) {
		switch op.Kind {
		case OpImm:
			if op.ImmRaw != "" {
				return ssaVal{}, fmt.Errorf("unresolved symbolic immediate %q", op.ImmRaw)
			}
			// Default immediates to i64; MOVL will cast to i32 as needed.
			return ssaVal{typ: I64, val: fmt.Sprintf("%d", op.Imm)}, nil
		case OpReg:
			v, ok := reg[op.Reg]
			if !ok {
				// Uninitialized register -> treat as 0 i64 for now.
				return ssaVal{typ: I64, val: "0"}, nil
			}
			return v, nil
		case OpRegShift:
			v, err := valueOf(Operand{Kind: OpReg, Reg: op.Reg})
			if err != nil {
				return ssaVal{}, err
			}
			if arch != ArchARM {
				return ssaVal{}, fmt.Errorf("shift operand only modeled for arm in linear lowering: %s", op)
			}
			v, err = emitCast(v, I32)
			if err != nil {
				return ssaVal{}, err
			}
			var shiftVal string
			if op.ShiftReg != "" {
				sv, err := valueOf(Operand{Kind: OpReg, Reg: op.ShiftReg})
				if err != nil {
					return ssaVal{}, err
				}
				sv, err = emitCast(sv, I32)
				if err != nil {
					return ssaVal{}, err
				}
				shiftVal = sv.val
			} else {
				shiftVal = fmt.Sprintf("%d", op.ShiftAmount)
			}
			name := newTmp()
			switch op.ShiftOp {
			case ShiftLeft:
				fmt.Fprintf(b, "  %%%s = shl i32 %s, %s\n", name, v.val, shiftVal)
			case ShiftRight:
				fmt.Fprintf(b, "  %%%s = lshr i32 %s, %s\n", name, v.val, shiftVal)
			case ShiftArith:
				fmt.Fprintf(b, "  %%%s = ashr i32 %s, %s\n", name, v.val, shiftVal)
			case ShiftRotate:
				fmt.Fprintf(b, "  %%%s = call i32 @llvm.fshr.i32(i32 %s, i32 %s, i32 %s)\n", name, v.val, v.val, shiftVal)
			default:
				return ssaVal{}, fmt.Errorf("unsupported shift op %q", op.ShiftOp)
			}
			return ssaVal{typ: I32, val: "%" + name}, nil
		case OpFP:
			slot, ok := fpParamSlot(op.FPOffset)
			if ok {
				idx := slot.Index
				if idx < 0 || idx >= len(sig.Args) {
					return ssaVal{}, fmt.Errorf("%w: invalid FP argument index %d at offset %d", ErrProbeNeedsContext, idx, op.FPOffset)
				}
				arg := fmt.Sprintf("%%arg%d", idx)
				if slot.Field >= 0 {
					aggTy := sig.Args[idx]
					name := newTmp()
					fmt.Fprintf(b, "  %%%s = extractvalue %s %s, %d\n", name, aggTy, arg, slot.Field)
					return ssaVal{typ: slot.Type, val: "%" + name}, nil
				}
				return ssaVal{typ: slot.Type, val: arg}, nil
			}
			return ssaVal{}, fmt.Errorf("%w: unbound FP read at offset %d", ErrProbeNeedsContext, op.FPOffset)
		case OpMem:
			addr, err := addrOfMem(op.Mem)
			if err != nil {
				return ssaVal{typ: I64, val: "0"}, nil
			}
			p := newTmp()
			fmt.Fprintf(b, "  %%%s = inttoptr i64 %s to ptr\n", p, addr)
			ld := newTmp()
			fmt.Fprintf(b, "  %%%s = load i64, ptr %%%s\n", ld, p)
			return ssaVal{typ: I64, val: "%" + ld}, nil
		case OpSym:
			// Keep linear lowering permissive when symbol relocation is not modeled.
			_ = op
			return ssaVal{typ: I64, val: "0"}, nil
		default:
			return ssaVal{typ: I64, val: "0"}, nil
		}
	}

	setReg := func(r Reg, v ssaVal) error {
		if v.typ == "" {
			return fmt.Errorf("setReg(%s): missing type", r)
		}
		// Materialize constants into SSA to simplify later inline asm.
		if !isSSA(v.val) {
			name := newTmp()
			switch v.typ {
			case I1, I8, I16, I32, I64:
				fmt.Fprintf(b, "  %%%s = add %s %s, 0\n", name, v.typ, v.val)
				v.val = "%" + name
			case Ptr:
				if v.val == "null" {
					v.val = "null"
				} else {
					return fmt.Errorf("setReg(%s): unsupported non-SSA ptr %q", r, v.val)
				}
			default:
				fmt.Fprintf(b, "  %%%s = add i64 0, 0\n", name)
				v.val = "%" + name
				v.typ = I64
			}
		}
		reg[r] = v
		return nil
	}

	setResult := func(off int64, v ssaVal) error {
		idx, ty, ok := fpResultIndex(off)
		if !ok {
			return nil
		}
		if v.typ != ty {
			var err error
			v, err = emitCast(v, ty)
			if err != nil {
				return err
			}
		}
		results[idx] = v
		haveResult[idx] = true
		return nil
	}

	terminated := false
	for _, ins := range fn.Instrs {
		if annotateSource {
			asm.EmitIRSourceComment(b, ins.Raw)
		}
		switch ins.Op {
		case OpMRS, OpMOVD, OpMOVQ, OpMOVL, "MOVW", "MOVB", "MOVBU", OpADDQ, OpSUBQ, OpXORQ:
			if len(ins.Args) != 2 {
				return fmt.Errorf("%s expects 2 operands: %q", ins.Op, ins.Raw)
			}
		}
		switch ins.Op {
		case OpTEXT:
			continue
		case OpMRS:
			// ARM64: MRS <sysreg>, Rn
			src, dst := ins.Args[0], ins.Args[1]
			sysreg, valid := arm64.SystemRegOperand(src)
			if !valid || dst.Kind != OpReg {
				return fmt.Errorf("MRS expects ident, reg: %q", ins.Raw)
			}
			name := newTmp()
			// Read system register via inline asm.
			// Example: call i64 asm "mrs $0, MIDR_EL1", "=r"()
			fmt.Fprintf(b, "  %%%s = call i64 asm sideeffect %q, %q()\n", name, "mrs $0, "+sysreg, "=r")
			reg[dst.Reg] = ssaVal{typ: I64, val: "%" + name}
			continue
		case OpMOVD:
			// ARM64: MOVD src, dst
			src, dst := ins.Args[0], ins.Args[1]
			v, err := valueOf(src)
			if err != nil {
				return err
			}
			v, err = emitCast(v, I64)
			if err != nil {
				return err
			}
			switch dst.Kind {
			case OpReg:
				if err := setReg(dst.Reg, v); err != nil {
					return err
				}
			case OpFP:
				if err := setResult(dst.FPOffset, v); err != nil {
					return err
				}
			default:
				continue
			}
			continue
		case "MOVW":
			if arch != ArchARM {
				continue
			}
			src, dst := ins.Args[0], ins.Args[1]
			v, err := valueOf(src)
			if err != nil {
				return err
			}
			v, err = emitCast(v, I32)
			if err != nil {
				return err
			}
			switch dst.Kind {
			case OpReg:
				if err := setReg(dst.Reg, v); err != nil {
					return err
				}
			case OpFP:
				if err := setResult(dst.FPOffset, v); err != nil {
					return err
				}
			default:
				continue
			}
			continue
		case "MOVB", "MOVBU":
			if arch != ArchARM {
				continue
			}
			src, dst := ins.Args[0], ins.Args[1]
			v, err := valueOf(src)
			if err != nil {
				return err
			}
			v, err = emitCast(v, I8)
			if err != nil {
				return err
			}
			switch dst.Kind {
			case OpReg:
				if err := setReg(dst.Reg, v); err != nil {
					return err
				}
			case OpFP:
				if err := setResult(dst.FPOffset, v); err != nil {
					return err
				}
			default:
				continue
			}
			continue
		case OpMOVQ:
			src, dst := ins.Args[0], ins.Args[1]
			v, err := valueOf(src)
			if err != nil {
				return err
			}
			v, err = emitCast(v, I64)
			if err != nil {
				return err
			}
			switch dst.Kind {
			case OpReg:
				if err := setReg(dst.Reg, v); err != nil {
					return err
				}
			case OpFP:
				if err := setResult(dst.FPOffset, v); err != nil {
					return err
				}
			default:
				continue
			}

		case OpADDQ, OpSUBQ, OpXORQ:
			src, dst := ins.Args[0], ins.Args[1]
			if dst.Kind != OpReg {
				return fmt.Errorf("%s dst must be register in prototype: %s", ins.Op, dst.String())
			}
			lhs, err := valueOf(dst)
			if err != nil {
				return err
			}
			rhs, err := valueOf(src)
			if err != nil {
				return err
			}
			lhs, err = emitCast(lhs, I64)
			if err != nil {
				return err
			}
			rhs, err = emitCast(rhs, I64)
			if err != nil {
				return err
			}
			name := newTmp()
			switch ins.Op {
			case OpADDQ:
				fmt.Fprintf(b, "  %%%s = add i64 %s, %s\n", name, lhs.val, rhs.val)
			case OpSUBQ:
				fmt.Fprintf(b, "  %%%s = sub i64 %s, %s\n", name, lhs.val, rhs.val)
			case OpXORQ:
				fmt.Fprintf(b, "  %%%s = xor i64 %s, %s\n", name, lhs.val, rhs.val)
			}
			reg[dst.Reg] = ssaVal{typ: I64, val: "%" + name}
		case "ADD", "SUB", "AND", "ORR", "EOR", "RSB":
			if arch != ArchARM {
				continue
			}
			var lhs, rhs ssaVal
			var dst Operand
			switch len(ins.Args) {
			case 2:
				dst = ins.Args[1]
				if dst.Kind != OpReg {
					return fmt.Errorf("%s dst must be register: %s", ins.Op, ins.Raw)
				}
				var err error
				lhs, err = valueOf(dst)
				if err != nil {
					return err
				}
				rhs, err = valueOf(ins.Args[0])
				if err != nil {
					return err
				}
			case 3:
				dst = ins.Args[2]
				if dst.Kind != OpReg {
					return fmt.Errorf("%s dst must be register: %s", ins.Op, ins.Raw)
				}
				var err error
				lhs, err = valueOf(ins.Args[1])
				if err != nil {
					return err
				}
				rhs, err = valueOf(ins.Args[0])
				if err != nil {
					return err
				}
			default:
				return fmt.Errorf("%s expects 2 or 3 operands: %s", ins.Op, ins.Raw)
			}
			var err error
			lhs, err = emitCast(lhs, I32)
			if err != nil {
				return err
			}
			rhs, err = emitCast(rhs, I32)
			if err != nil {
				return err
			}
			name := newTmp()
			switch strings.ToUpper(string(ins.Op)) {
			case "ADD":
				fmt.Fprintf(b, "  %%%s = add i32 %s, %s\n", name, lhs.val, rhs.val)
			case "SUB":
				fmt.Fprintf(b, "  %%%s = sub i32 %s, %s\n", name, lhs.val, rhs.val)
			case "AND":
				fmt.Fprintf(b, "  %%%s = and i32 %s, %s\n", name, lhs.val, rhs.val)
			case "ORR":
				fmt.Fprintf(b, "  %%%s = or i32 %s, %s\n", name, lhs.val, rhs.val)
			case "EOR":
				fmt.Fprintf(b, "  %%%s = xor i32 %s, %s\n", name, lhs.val, rhs.val)
			case "RSB":
				fmt.Fprintf(b, "  %%%s = sub i32 %s, %s\n", name, rhs.val, lhs.val)
			}
			reg[dst.Reg] = ssaVal{typ: I32, val: "%" + name}
			continue

		case OpMOVL:
			src, dst := ins.Args[0], ins.Args[1]
			v, err := valueOf(src)
			if err != nil {
				return err
			}
			v, err = emitCast(v, I32)
			if err != nil {
				return err
			}
			switch dst.Kind {
			case OpReg:
				if err := setReg(dst.Reg, v); err != nil {
					return err
				}
			case OpFP:
				if err := setResult(dst.FPOffset, v); err != nil {
					return err
				}
			default:
				continue
			}

		case OpCPUID:
			// x86: CPUID reads EAX/ECX and writes EAX/EBX/ECX/EDX.
			eax := reg[AX]
			if eax.typ == "" {
				z, _ := zero(I32)
				eax = z
			} else {
				var err error
				eax, err = emitCast(eax, I32)
				if err != nil {
					return err
				}
			}
			ecx := reg[CX]
			if ecx.typ == "" {
				z, _ := zero(I32)
				ecx = z
			} else {
				var err error
				ecx, err = emitCast(ecx, I32)
				if err != nil {
					return err
				}
			}
			if !isSSA(eax.val) {
				if err := setReg(AX, eax); err != nil {
					return err
				}
				eax = reg[AX]
			}
			if !isSSA(ecx.val) {
				if err := setReg(CX, ecx); err != nil {
					return err
				}
				ecx = reg[CX]
			}
			call := newTmp()
			// Return 4x i32 in EAX/EBX/ECX/EDX.
			fmt.Fprintf(b, "  %%%s = call { i32, i32, i32, i32 } asm sideeffect %q, %q(i32 %s, i32 %s)\n",
				call,
				"cpuid",
				"={ax},={bx},={cx},={dx},{ax},{cx},~{dirflag},~{fpsr},~{flags}",
				eax.val, ecx.val)
			ext := func(i int) string {
				n := newTmp()
				fmt.Fprintf(b, "  %%%s = extractvalue { i32, i32, i32, i32 } %%%s, %d\n", n, call, i)
				return "%" + n
			}
			reg[AX] = ssaVal{typ: I32, val: ext(0)}
			reg[BX] = ssaVal{typ: I32, val: ext(1)}
			reg[CX] = ssaVal{typ: I32, val: ext(2)}
			reg[DX] = ssaVal{typ: I32, val: ext(3)}

		case OpXGETBV:
			// x86: XGETBV reads ECX and writes EAX/EDX.
			ecx := reg[CX]
			if ecx.typ == "" {
				z, _ := zero(I32)
				ecx = z
			} else {
				var err error
				ecx, err = emitCast(ecx, I32)
				if err != nil {
					return err
				}
			}
			if !isSSA(ecx.val) {
				if err := setReg(CX, ecx); err != nil {
					return err
				}
				ecx = reg[CX]
			}
			call := newTmp()
			fmt.Fprintf(b, "  %%%s = call { i32, i32 } asm sideeffect %q, %q(i32 %s)\n",
				call,
				"xgetbv",
				"={ax},={dx},{cx},~{dirflag},~{fpsr},~{flags}",
				ecx.val)
			eaxN := newTmp()
			edxN := newTmp()
			fmt.Fprintf(b, "  %%%s = extractvalue { i32, i32 } %%%s, 0\n", eaxN, call)
			fmt.Fprintf(b, "  %%%s = extractvalue { i32, i32 } %%%s, 1\n", edxN, call)
			reg[AX] = ssaVal{typ: I32, val: "%" + eaxN}
			reg[DX] = ssaVal{typ: I32, val: "%" + edxN}

		case OpRET:
			// Return value comes either from explicit result slots (name+off(FP))
			// or, as a fallback, from the arch return register for scalar returns.
			switch {
			case sig.Ret == Void:
				b.WriteString("  ret void\n")
			case len(sig.Frame.Results) > 1:
				// Aggregate return.
				cur := "undef"
				last := ""
				for _, slot := range sig.Frame.Results {
					i := slot.Index
					v := ssaVal{typ: slot.Type, val: "0"}
					if haveResult[i] {
						v = results[i]
					} else {
						z, err := zero(slot.Type)
						if err != nil {
							return err
						}
						v = z
					}
					if v.typ != slot.Type {
						var err error
						v, err = emitCast(v, slot.Type)
						if err != nil {
							return err
						}
					}
					if !isSSA(v.val) {
						// insertvalue accepts constants, but normalize to SSA for consistency.
						name := newTmp()
						fmt.Fprintf(b, "  %%%s = add %s %s, 0\n", name, v.typ, v.val)
						v.val = "%" + name
					}
					name := newTmp()
					fmt.Fprintf(b, "  %%%s = insertvalue %s %s, %s %s, %d\n", name, sig.Ret, cur, slot.Type, v.val, i)
					cur = "%" + name
					last = cur
				}
				fmt.Fprintf(b, "  ret %s %s\n", sig.Ret, last)
			default:
				// Scalar return.
				var v ssaVal
				if len(sig.Frame.Results) == 1 && haveResult[0] {
					v = results[0]
				} else if rv, ok := reg[archReturnReg(arch)]; ok {
					v = rv
				} else {
					z, err := zero(sig.Ret)
					if err != nil {
						return err
					}
					v = z
				}
				if v.typ != sig.Ret {
					var err error
					v, err = emitCast(v, sig.Ret)
					if err != nil {
						return err
					}
				}
				fmt.Fprintf(b, "  ret %s %s\n", sig.Ret, v.val)
			}
			terminated = true

		case OpBYTE:
			// Ignore raw machine bytes for now (prototype).
			continue
		default:
			// Keep linear lowering permissive for legacy/x86 stubs.
			continue
		}
		if terminated {
			break
		}
	}
	if !terminated {
		if sig.Ret == Void {
			b.WriteString("  ret void\n")
		} else {
			fmt.Fprintf(b, "  ret %s %s\n", sig.Ret, asm.LLVMZeroValue(sig.Ret))
		}
	}

	b.WriteString("}\n")
	return nil
}

func archReturnReg(arch Arch) Reg {
	if arch == ArchARM || arch == ArchARM64 {
		return Reg("R0")
	}
	return AX
}

