func TestX86LegacyPackedMoveGrammarEffectAndMemoryShapeAgree(t *testing.T) {
	for _, arch := range []string{"amd64", "386"} {
		for _, op := range x86LegacyPackedMoveTestNames {
			for _, operands := range []string{
				"X0,X1", "(AX),X1", "8(AX)(CX*4),X1", "a+0(FP),X1", "value-32(SP),X1", "·data(SB),X1",
				"X0,(AX)", "X0,8(AX)(CX*4)", "X0,a+0(FP)", "X0,value-32(SP)", "X0,·data(SB)",
			} {
				t.Run(arch+"/"+op+" "+operands, func(t *testing.T) {
					file, err := Parse(ArchAMD64, "TEXT ·Value(SB),4,$64-64\n"+op+" "+operands+"\nRET\n")
					if err != nil {
						t.Fatal(err)
					}
					ins := file.Funcs[0].Instrs[1]
					before := fmt.Sprintf("%#v", ins)
					form, recognized, err := x86LegacyPackedMoveProperties(ins.Op, ins, arch)
					if !recognized || err != nil {
						t.Fatal("accepted Go shape lost", form, err)
					}
					effect, recognized, err := x86TypedInstructionByteEffect(ins.Op, ins, arch)
					if !recognized || err != nil || len(effect.operands) != 2 || effect.flagsDefined != 0 || effect.flagsKilled != 0 {
						t.Fatal("whole move gained arithmetic or lost effects", effect, err)
					}
					for index, role := range effect.operands {
						if role.index != index || role.width != 16 || role.read != (index == 0) || role.write != (index == 1) ||
							!reflect.DeepEqual(role.operand, ins.Args[index]) {
							t.Fatalf("incomplete ordered byte effect: %#v", role)
						}
						width, write, known := x86InstructionMemoryShape(ins, index, arch)
						if known != (form.memory == index) || known && (width != 16 || write != form.memoryWrite) {
							t.Fatalf("memory shape differs from descriptor: %d/%t/%t %#v", width, write, known, form)
						}
						if ins.Args[index].Kind == OpFP {
							width, write, known := X86FPAccessBytes(ins, index, arch)
							if !known || width != 16 || write != (index == 1) {
								t.Fatal("FP observer has a different native width", width, write, known)
							}
						}
						// Typed caller recognition is not a standalone source-stack
						// or memory permission; the complete actual caller remains
						// mandatory before the private transfer can be consumed.
						if !x86CallerVectorMoveKnown(ins) || x86SourceStackInstructionKnown(ins, "MOVQ", "Q", arch) {
							t.Fatal("legacy move lost typed caller registration or granted a non-caller source stack")
						}
					}
					if before != fmt.Sprintf("%#v", ins) {
						t.Fatal("descriptor changed original source/operands")
					}
				})
			}
		}
	}
}

func TestX86LegacyPackedMoveActualGoCompleteOpcodeBytes(t *testing.T) {
	// Independent opcode bytes, not a table generated by the descriptor.
	for _, arch := range []string{"amd64", "386"} {
		for _, row := range []struct {
			name        string
			prefix      []byte
			load, store byte
		}{
			{"MOVOU", []byte{0xf3}, 0x6f, 0x7f}, {"MOVOA", []byte{0x66}, 0x6f, 0x7f}, {"MOVO", []byte{0x66}, 0x6f, 0x7f},
			{"MOVUPS", nil, 0x10, 0x11}, {"MOVAPS", nil, 0x28, 0x29},
			{"MOVUPD", []byte{0x66}, 0x10, 0x11}, {"MOVAPD", []byte{0x66}, 0x28, 0x29},
		} {
			for _, operands := range []struct {
				text  string
				modrm byte
				store bool
			}{
				{"X1,X0", 0xc1, false}, {"X0,X7", 0xf8, false},
				{"(AX),X1", 0x08, false}, {"X1,(AX)", 0x08, true},
			} {
				t.Run(arch+"/"+row.name+" "+operands.text, func(t *testing.T) {
					source := "TEXT probe(SB),4,$0-0\n" + row.name + " " + operands.text + "\nRET\n"
					goAssemblerOracleOutput(t, arch, source, "", true)
					want := append([]byte(nil), row.prefix...)
					opcode := row.load
					if operands.store {
						opcode = row.store
					}
					want = append(want, 0x0f, opcode, operands.modrm, 0xc3)
					if got := x86PackedShiftActualGoBytes(t, arch, source); !bytes.Equal(got, want) {
						t.Fatalf("original Go machine bank/width differs: %x want %x", got, want)
					}
				})
			}
		}
	}
}

func TestX86LegacyPackedMoveMode32BanksMatchOriginalGo(t *testing.T) {
	for _, op := range x86LegacyPackedMoveTestNames {
		for _, operands := range []string{"X8,X0", "X0,X15", "a+0(FP),X8", "X15,a+0(FP)"} {
			t.Run(op+" "+operands, func(t *testing.T) {
				source := "TEXT ·Value(SB),4,$0-32\n" + op + " " + operands + "\nRET\n"
				goAssemblerOracleOutput(t, "386", source, "", false)
				goAssemblerOracleOutput(t, "amd64", source, "", true)
				file, err := Parse(ArchAMD64, source)
				if err != nil {
					t.Fatal(err)
				}
				ins := file.Funcs[0].Instrs[1]
				if _, recognized, err := x86LegacyPackedMoveProperties(ins.Op, ins, "amd64"); !recognized || err != nil {
					t.Fatal("AMD64 high-bank accepted format omitted", err)
				}
				if _, recognized, err := x86TypedInstructionByteEffect(ins.Op, ins, "386"); !recognized || err == nil {
					t.Fatal("mode32 name acquired a fake physical value", err)
				}
				for _, triple := range []string{"i386-unknown-linux-gnu", "i686-pc-windows-msvc"} {
					options := Options{Goarch: "386", TargetTriple: triple, Sigs: map[string]FuncSig{"Value": {Ret: Void}},
						ResolveSym: func(symbol string) string { return strings.TrimPrefix(symbol, "·") }}
					if _, err := Translate(file, options); err == nil {
						t.Fatal("text API granted physical high X", err)
					}
					ctx := llvm.NewContext()
					func() {
						defer ctx.Dispose()
						module, err := TranslateModuleInContext(ctx, file, options)
						if !module.IsNil() {
							defer module.Dispose()
						}
						if err == nil {
							t.Fatal("module API granted physical high X", err)
						}
						pkg := mustGoPackage(t, "example.invalid/move", "package move\nfunc Value(a,b,c,d uint64)\n")
						translated, err := translateGoModuleInContext(ctx, pkg, []byte(source), GoModuleOptions{
							GOARCH: "386", TargetTriple: triple, ResolveSym: options.ResolveSym,
						})
						if translated != nil && !translated.Module.IsNil() {
							defer translated.Module.Dispose()
						}
						if err == nil {
							t.Fatal("Go API granted physical high X", err)
						}
					}()
				}
			})
		}
	}
}

func TestX86LegacyPackedMoveThreeAPIFiveTargetObjects(t *testing.T) {
	llc := findLLVM22Tool("llc")
	if llc == "" {
		t.Fatal("LLVM22 llc required")
	}
	for _, target := range []struct{ arch, triple string }{
		{"amd64", "x86_64-apple-darwin"}, {"amd64", "x86_64-unknown-linux-gnu"}, {"amd64", "x86_64-pc-windows-msvc"},
		{"386", "i386-unknown-linux-gnu"}, {"386", "i686-pc-windows-msvc"},
	} {
		for _, op := range x86LegacyPackedMoveTestNames {
			t.Run(target.triple+"/"+op, func(t *testing.T) {
				// This is the numerical FP/result contract. Native memory
				// opcodes have their own complete three-API object matrix.
				fpMove := op
				if op == "MOVO" || op == "MOVOA" || op == "MOVAPS" || op == "MOVAPD" {
					fpMove = "MOVOU"
				}
				body := "MOVSD c+16(FP),X1\n" + fpMove + " a+0(FP),X0\n" + op + " X1,X0\n" + op + " X0,X0\nMOVSD X0,ret0+32(FP)\nRET"
				pkg, file, sig, source := x86ResultInitializationFixture(t, target.arch, "func Value(a,b,c,d uint64) uint64", body)
				goAssemblerOracleOutput(t, target.arch, source, "", true)
				if err := CheckX86ABI0ResultInitialization(file.Funcs[0], sig, target.arch); err != nil {
					t.Fatal(err)
				}
				options := Options{Goarch: target.arch, TargetTriple: target.triple, Sigs: map[string]FuncSig{"Value": sig},
					ResolveSym: func(symbol string) string { return strings.TrimPrefix(symbol, "·") }}
				before := fmt.Sprintf("%#v %#v", file, sig)
				ir, err := Translate(file, options)
				if err != nil {
					t.Fatal(err)
				}
				x86ResultInitializationObject(t, llc, target.triple, ir, "text")
				ctx := llvm.NewContext()
				defer ctx.Dispose()
				module, err := TranslateModuleInContext(ctx, file, options)
				if !module.IsNil() {
					defer module.Dispose()
				}
				if err != nil {
					t.Fatal(err)
				}
				x86ResultInitializationObject(t, llc, target.triple, module.String(), "module")
				translated, err := translateGoModuleInContext(ctx, pkg, []byte(source), GoModuleOptions{
					GOARCH: target.arch, TargetTriple: target.triple, ResolveSym: options.ResolveSym,
				})
				if translated != nil && !translated.Module.IsNil() {
					defer translated.Module.Dispose()
				}
				if err != nil {
					t.Fatal(err)
				}
				x86ResultInitializationObject(t, llc, target.triple, translated.Module.String(), "typed-go")
				if before != fmt.Sprintf("%#v %#v", file, sig) {
					t.Fatal("API changed original source or signature")
				}
			})
		}
	}
}

func TestX86LegacyPackedMoveDispatchAndMalformedFormsDoNotEmit(t *testing.T) {
	for _, op := range x86LegacyPackedMoveTestNames {
		for _, operands := range []string{"M0,M1", "AX,X0", "X0,AX", "$1,X0", "Y0,Y1", "Z0,Z1", "X16,X0", "(AX),(BX)", "X0,K1,X1"} {
			file, err := Parse(ArchAMD64, "TEXT probe(SB),4,$0-0\n"+op+" "+operands+"\nRET\n")
			if err != nil {
				t.Fatal(err)
			}
			ins := file.Funcs[0].Instrs[1]
			if _, recognized, err := x86TypedInstructionByteEffect(ins.Op, ins, "amd64"); !recognized || err == nil {
				t.Fatal("Go-rejected form acquired a byte effect", ins, err)
			}
			ctx, output := newAMD64CtxWithFuncForTest(t, file.Funcs[0], FuncSig{Ret: Void}, nil)
			before, temporary := output.String(), ctx.tmp
			if known, term, err := ctx.lowerVec(ins.Op, ins); !known || term || err == nil || output.String() != before || ctx.tmp != temporary {
				t.Fatal("malformed whole move emitted partial IR", known, term, err)
			}
		}
		file, err := Parse(ArchAMD64, "TEXT probe(SB),4,$0-0\n"+op+" X0,X1\nRET\n")
		if err != nil {
			t.Fatal(err)
		}
		for _, identity := range []Op{"", Op(op), Op(strings.ToLower(op))} {
			ins := file.Funcs[0].Instrs[1]
			ins.Op = identity
			if _, recognized, err := x86LegacyPackedMoveProperties(Op(op), ins, "amd64"); !recognized || err != nil {
				t.Fatal("legacy matching dispatch changed", identity, err)
			}
		}
		ins := file.Funcs[0].Instrs[1]
		ins.Op = "MOVQ"
		if _, recognized, err := x86TypedInstructionByteEffect(Op(op), ins, "amd64"); !recognized || err == nil {
			t.Fatal("contradictory instruction got an effect", err)
		}
	}
}
