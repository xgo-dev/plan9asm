func arm64ClosedTailOriginalPackage(t *testing.T, family string) (GoPackage, []byte) {
	t.Helper()
	root := filepath.Join(runtime.GOROOT(), "src", "internal", "bytealg")
	declPath := filepath.Join(root, family+"_native.go")
	asmPath := filepath.Join(root, family+"_arm64.s")
	decl, err := os.ReadFile(declPath)
	if err != nil {
		t.Fatal(err)
	}
	source, err := os.ReadFile(asmPath)
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	parsed, err := parser.ParseFile(fset, declPath, decl, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	conf := types.Config{Importer: importer.Default()}
	checked, err := conf.Check("internal/bytealg", fset, []*ast.File{parsed}, nil)
	if err != nil {
		t.Fatal(err)
	}
	// Retain the original include bytes. The header is generated by the actual
	// compiler from the original declaration, not a guessed empty go_asm.h.
	dir := t.TempDir()
	run := func(args ...string) {
		t.Helper()
		ctx, cancel := runtimeOracleStageContext(t)
		defer cancel()
		command := exec.CommandContext(ctx, "go", args...)
		command.Env = append(os.Environ(), "GOARCH=arm64", "GOOS=linux")
		if out, err := runtimeOracleCombinedOutput(ctx, command); err != nil {
			t.Fatalf("actual selected SDK original %s object: %v\n%s", family, err, out)
		}
	}
	run("tool", "compile", "-p", "internal/bytealg", "-asmhdr", filepath.Join(dir, "go_asm.h"), "-o", filepath.Join(dir, "decl.o"), declPath)
	args := append(arm64ClosureGoAsmArgs(t), "-I", filepath.Join(runtime.GOROOT(), "pkg", "include"), "-I", dir, "-o", filepath.Join(dir, "original.o"), asmPath)
	run(args...)
	for path, original := range map[string][]byte{declPath: decl, asmPath: source} {
		after, err := os.ReadFile(path)
		if err != nil || sha256.Sum256(after) != sha256.Sum256(original) {
			t.Fatalf("original SDK source changed while compiling %s: %v", path, err)
		}
	}
	return GoPackage{Path: checked.Path(), Types: checked, Syntax: []*ast.File{parsed}}, source
}

func TestARM64ClosedTailOriginalCompareAllAPIsObjects(t *testing.T) {
	pkg, source := arm64ClosedTailOriginalPackage(t, "compare")
	llc := findLLVM22Tool("llc")
	if llc == "" {
		t.Fatal("LLVM22 llc is required")
	}
	for _, target := range []string{
		"aarch64-apple-darwin", "aarch64-unknown-linux-gnu", "aarch64-unknown-linux-musl",
		"aarch64-unknown-freebsd", "aarch64-pc-windows-msvc",
	} {
		t.Run(target, func(t *testing.T) {
			ctx := llvm.NewContext()
			defer ctx.Dispose()
			bound, err := translateGoModuleInContext(ctx, pkg, source, GoModuleOptions{
				GOARCH: "arm64", TargetTriple: target, ResolveSym: arm64ClosureResolve,
			})
			if bound != nil && !bound.Module.IsNil() {
				defer bound.Module.Dispose()
			}
			if err != nil {
				t.Fatal(err)
			}
			file, err := Parse(ArchARM64, string(source))
			if err != nil {
				t.Fatal(err)
			}
			options := Options{Goarch: "arm64", TargetTriple: target, ResolveSym: arm64ClosureResolve, Sigs: bound.Signatures}
			text, err := Translate(file, options)
			if err != nil {
				t.Fatal(err)
			}
			module, err := TranslateModuleInContext(ctx, file, options)
			if !module.IsNil() {
				defer module.Dispose()
			}
			if err != nil {
				t.Fatal(err)
			}
			if indirectMarkerComparableIR(text) != indirectMarkerComparableIR(bound.Module.String()) ||
				indirectMarkerComparableIR(text) != indirectMarkerComparableIR(module.String()) {
				t.Fatal("three public APIs disagree on the complete original SDK source")
			}
			compileLLVMToObject(t, llc, target, "original-compare.ll", "original-compare.o", text)
		})
	}
}
